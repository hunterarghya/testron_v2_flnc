"""Write a production env file with fresh secrets (docs/hosting_guide.md, ADR-086).

    production: deploy/oracle/.env, with the values you must fill in marked FILL_ME. Also what
                you paste into Render's "Environment" page.
    local-prod: deploy/oracle/.env.localprod, complete, for trying the production setup on
                this PC (`just prod-local`).

An existing file is never overwritten: its keys may already protect real data (a new
ASSIGNMENT_PASSWORD_KEY would make every stored test password unreadable).

Usage: python scripts/make_env.py production --domain tests.example.com
           --teacher-email teacher@example.com --teacher-name "Mrs Sen"
       python scripts/make_env.py local-prod
"""

import argparse
import base64
import os
import secrets
import sys
from pathlib import Path

DEPLOY = Path(__file__).resolve().parents[1] / "deploy" / "oracle"
FILL_ME = "FILL_ME"
# Shown on the line above each value: comments after a value aren't read the same everywhere
NOTES = {
    "DATABASE_URL": "Neon's pooled connection string (its host contains -pooler)",
    "DATABASE_URL_DIRECT": "The same connection string without -pooler (migrations only)",
    "TEACHER_INITIAL_PASSWORD": "Used only when the teacher is first created; delete after",
    "EMAIL_URL": "e.g. smtp+tls://LOGIN:SMTP_KEY@smtp-relay.brevo.com:587 (port 2525 on Render)",
    "EMAIL_FROM": "A sender address your email service has verified",
    "IMAGEKIT_URL_ENDPOINT": "https://ik.imagekit.io/<your ImageKit id>",
    "MIGRATE_ON_START": "1: migrate and seed at each start (needed on Render free; fine on a VM)",
}


def fresh_secrets() -> dict[str, str]:
    return {
        "SECRET_KEY": secrets.token_urlsafe(64),
        # A Fernet key: 32 random bytes, URL-safe base64 (ADR-018)
        "ASSIGNMENT_PASSWORD_KEY": base64.urlsafe_b64encode(os.urandom(32)).decode(),
        "OTP_HMAC_KEY": secrets.token_urlsafe(48),
        "BACKOFFICE_PATH": f"backoffice-{secrets.token_hex(8)}",
    }


def production(domain: str, teacher_email: str, teacher_name: str) -> dict[str, str]:
    return {
        "DJANGO_ENV": "prod",
        "DEBUG": "False",
        "APP_DOMAIN": domain,
        "ALLOWED_HOSTS": domain,
        "CSRF_TRUSTED_ORIGINS": f"https://{domain}",
        **fresh_secrets(),
        "DATABASE_URL": FILL_ME,
        "DATABASE_URL_DIRECT": FILL_ME,
        "TEACHER_EMAIL": teacher_email,
        "TEACHER_NAME": f'"{teacher_name}"',
        "TEACHER_INITIAL_PASSWORD": secrets.token_urlsafe(12),
        "EMAIL_URL": FILL_ME,
        "EMAIL_FROM": f'"Tests <{FILL_ME}>"',
        "MEDIA_BACKEND": "imagekit",
        "IMAGEKIT_PUBLIC_KEY": FILL_ME,
        "IMAGEKIT_PRIVATE_KEY": FILL_ME,
        "IMAGEKIT_URL_ENDPOINT": FILL_ME,
        "WEB_CONCURRENCY": "2",
        "TRUSTED_PROXY_HOPS": "1",
        "MIGRATE_ON_START": "1",
        "E2E_TEST_HOOKS": "0",
    }


def local_prod() -> dict[str, str]:
    values = production("localhost", "teacher@example.com", "Local Teacher")
    values.update(
        {
            "APP_ENV_FILE": ".env.localprod",
            # compose.local.yml points these at the local containers
            "DATABASE_URL": "postgres://app:app@postgres:5432/app",
            "DATABASE_URL_DIRECT": "postgres://app:app@postgres:5432/app",
            "TEACHER_INITIAL_PASSWORD": secrets.token_urlsafe(12),
            "EMAIL_URL": "smtp://mailpit:1025",
            "EMAIL_FROM": '"Tests <noreply@localhost>"',
            # Uploads can't work without a real ImageKit account; everything else does
            "IMAGEKIT_PUBLIC_KEY": "public_local_placeholder",
            "IMAGEKIT_PRIVATE_KEY": "private_local_placeholder",
            "IMAGEKIT_URL_ENDPOINT": "https://ik.imagekit.io/local-placeholder",
        }
    )
    return values


def write(path: Path, values: dict[str, str]) -> None:
    if path.exists():
        sys.exit(f"{path} already exists; delete it first if you really want new secrets.")
    lines = [
        "# Generated by scripts/make_env.py. Secret: never commit, share or paste in chats.",
        *(line for key, value in values.items() for line in _entry(key, value)),
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    sys.stdout.write(f"Wrote {path}\n")
    missing = [key for key, value in values.items() if value.startswith(FILL_ME)]
    if missing:
        sys.stdout.write(f"Fill in: {', '.join(missing)}\n")
    sys.stdout.write(f"The teacher's first password is TEACHER_INITIAL_PASSWORD in {path.name}.\n")


def _entry(key: str, value: str) -> list[str]:
    note = [f"# {NOTES[key]}"] if key in NOTES else []
    return [*note, f"{key}={value}"]


def main() -> None:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    sub = parser.add_subparsers(dest="kind", required=True)
    prod = sub.add_parser("production")
    prod.add_argument("--domain", required=True)
    prod.add_argument("--teacher-email", required=True)
    prod.add_argument("--teacher-name", required=True)
    sub.add_parser("local-prod")
    args = parser.parse_args()
    if args.kind == "production":
        write(DEPLOY / ".env", production(args.domain, args.teacher_email, args.teacher_name))
    else:
        write(DEPLOY / ".env.localprod", local_prod())


if __name__ == "__main__":
    main()
